def message(language, key):
    selected = language if language in MESSAGES else 'ru'
    return MESSAGES[selected][key]


def help_text(language, shop_in_chat=False):
    """What the bot can do, named after the buttons the shopper sees right now."""
    def say(key, *buttons):
        return message(language, key).format(*(message(language, button) for button in buttons))
    shop = say('help_shop', 'menu_catalog', 'menu_cart') if shop_in_chat else say('help_store', 'menu_store')
    return '\n'.join((
        say('help_title'), say('help_search'), shop, say('help_orders', 'menu_orders'),
        say('help_notifications', 'menu_notifications'), say('help_language', 'menu_language'),
    ))


def catalogs_match():
    return set(MESSAGES['ru']) == set(MESSAGES['uz'])


def commands(language):
    descriptions = {
        'ru': ('Начать', 'Мои заказы', 'Выбрать язык', 'Уведомления', 'Помощь', 'Отключить рекламу'),
        'uz': ('Boshlash', 'Buyurtmalarim', 'Tilni tanlash', 'Bildirishnomalar', 'Yordam', 'Reklamani o‘chirish'),
    }[language]
    names = ('start', 'orders', 'language', 'notifications', 'help', 'stop')
    return [{'command': name, 'description': description} for name, description in zip(names, descriptions)]
